export const getSoireeBySlug = (slug) =>
  soirees.find((soiree) => soiree.slug === slug);

export const getSoireesBySerie = (serieSlug) =>
  soirees.filter((soiree) => soiree.serieSlug === serieSlug);

export const getSoireesByPeriod = (period) =>
  soirees.filter((soiree) => soiree.period === period);

export const getSoireesByCategory = (category) =>
  soirees.filter((soiree) => soiree.category === category);

export const getLatestSoirees = (limit = 3) =>
  [...soirees]
    .filter((soiree) => soiree.dateISO)
    .sort((a, b) => new Date(b.dateISO) - new Date(a.dateISO))
    .slice(0, limit);